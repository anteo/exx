// This grammar provides editor structure and highlighting. EXX checks the ABI
// and instruction operands when it translates the source.
const binaryOperators = [
  ['||'], ['&&'], ['|'], ['^'], ['&'], ['==', '!='],
  ['<', '<=', '>', '>='], ['<<', '>>'], ['+', '-'],
];

const commaSep = rule => optional(seq(rule, repeat(seq(',', rule))));

module.exports = grammar({
  name: 'exx',
  extras: $ => [/\s/, $.line_comment, $.block_comment],
  word: $ => $.identifier,

  rules: {
    source_file: $ => repeat(choice($.procedure, $.external_procedure,
      $.data_declaration, $.field_declaration, $.layout_declaration, $.struct_declaration,
      $.constant_declaration, $.origin_declaration, $.abi_use, $.assembly, ';')),

    procedure: $ => seq($._signature, optional($.frame), optional($.clobbers), $.block),
    external_procedure: $ => seq('extern', $._signature, optional($.clobbers)),
    _signature: $ => seq(optional($.procedure_results), field('name', $.identifier),
      '(', commaSep($.parameter), ')'),
    procedure_results: $ => choice($.identifier,
      seq('(', $.identifier, repeat1(seq(',', $.identifier)), ')')),
    parameter: $ => seq(field('name', $.identifier), choice(
      seq($.arrow, $.identifier),
      seq($._type_annotation, optional(seq($.arrow, choice($.identifier, $.stack_slot)))),
    )),
    stack_slot: $ => seq('stack', '[', $.number, ']'),
    frame: $ => seq('frame', '(', $.identifier, ')'),
    _type_annotation: $ => seq(':', field('type', choice($.builtin_type, $.type_name))),
    type_name: $ => seq($.identifier, repeat(seq('.', $.identifier))),
    builtin_type: _ => choice('u8', 'u16'),
    assembly_outputs: $ => seq($.arrow, choice($._assembly_location, $.assembly_name_list)),
    assembly_clobbers: $ => seq('clobbers', $.assembly_name_list),
    assembly_name_list: $ => seq('(', commaSep($._assembly_location), ')'),
    _assembly_location: $ => choice($.identifier, $.qualified_name),
    clobbers: $ => seq('clobbers', $.name_list),
    name_list: $ => seq('(', commaSep($.identifier), ')'),
    arrow: _ => choice('→', '->'),

    data_declaration: $ => choice(
      seq('data', field('name', $.identifier), $._type_annotation, '=', $._expression),
      seq('extern', 'data', field('name', $.identifier), optional($._type_annotation)),
    ),
    field_declaration: $ => seq('field', choice($._field_entry,
      seq('{', repeat(choice($._field_entry, ',', ';')), '}'))),
    _field_entry: $ => choice(seq($.qualified_name, $._type_annotation), seq($.type_name, $.record_fields)),
    layout_declaration: $ => seq('layout', choice($._layout_entry,
      seq('{', repeat(choice($._layout_entry, ',', ';')), '}'))),
    _layout_entry: $ => seq($.type_name, ':', $.number, optional($.record_fields)),
    struct_declaration: $ => seq('struct', $.type_name, $.record_fields),
    record_fields: $ => seq('{', repeat(choice($.member_declaration, ',', ';')), '}'),
    member_declaration: $ => seq(field('name', $.identifier), $._type_annotation),
    constant_declaration: $ => seq('const', choice($.constant_entry,
      seq('{', repeat(choice($.constant_entry, ',', ';')), '}'))),
    constant_entry: $ => seq(field('name', $.identifier), '=', $._expression),
    origin_declaration: $ => seq('origin', $._expression),
    abi_use: $ => seq('use', choice($.abi_path, seq('{', repeat(choice($.abi_path, ',', ';')), '}'))),
    abi_path: _ => /"([^"\\\r\n]|\\["\\])*"/,
    qualified_name: $ => seq($.identifier, repeat1(seq('.', $.identifier))),

    block: $ => seq('{', repeat(choice($._statement, ';')), '}'),
    _statement: $ => choice(
      $.if_statement, $.loop_statement, $.keep_statement, $.assembly,
      $.label, $.goto_statement, $.return_statement, 'break',
      $.assignment, $.binding, prec(1, choice($.call, $.prefix_update, $.postfix_update)),
    ),
    _body: $ => prec.right(choice($.block, seq($._statement, optional(';')))),
    if_statement: $ => prec.right(seq('if', '(', $._expression, ')', $._body,
      optional(seq('else', $._body)))),
    loop_statement: $ => choice(
      seq(choice('while', 'repeat'), '(', $._expression, ')', $._body),
      seq('do', $.block, 'while', '(', $._expression, ')'),
    ),
    keep_statement: $ => seq('keep', $.name_list, $.block),
    label: $ => seq(field('name', $.identifier), ':'),
    goto_statement: $ => seq('goto', field('target', $.identifier)),
    return_statement: $ => prec.right(seq('return', optional(choice(
      token.immediate(prec(1, /[ \t]*(\r\n?|\n)/)), $._expression)))),
    assignment: $ => seq($._expression, $.assignment_operator, $._expression),
    binding: $ => seq($._expression, '→', choice($.identifier, $.name_list)),
    assignment_operator: _ => choice('=', '^=', '+=', '-=', '&=', '|=', '<<=', '>>='),

    _expression: $ => choice($.assignment_expression, $.binary_expression,
      $.unary_expression, $.prefix_update, $.postfix_update,
      $.index_expression, $.bit_expression, $._atom),
    _atom: $ => choice($.identifier, $.qualified_name, $.access, $.call,
      $.number, $.boolean, $.tuple_or_group),
    tuple_or_group: $ => seq('(', commaSep($._expression), ')'),
    assignment_expression: $ => seq('(', choice($.identifier, $.qualified_name), '=', $._expression, ')'),
    binary_expression: $ => choice(...binaryOperators.map((operators, index) =>
      prec.left(index + 1, seq($._expression,
        operators.length === 1 ? operators[0] : choice(...operators), $._expression)))),
    unary_expression: $ => prec(10, seq(choice('!', '~', '+', '-', '*', '&'), $._expression)),
    prefix_update: $ => prec(10, seq(choice('++', '--'), $._expression)),
    postfix_update: $ => prec.left(13, seq($._expression, $.postfix_operator)),
    postfix_operator: _ => token.immediate(/[ \t]*(\+\+|--)/),
    index_expression: $ => prec(11, seq($._expression, '[', $._expression, ']')),
    bit_expression: $ => prec(12, seq($._expression, '$', $._atom)),
    access: $ => seq(choice($.identifier, $.qualified_name), '->',
      field('member', $.identifier), repeat(seq('.', field('member', $.identifier)))),
    call: $ => prec(1, seq(field('function', choice($.identifier, $.qualified_name)),
      '(', commaSep($._call_argument), ')')),
    _call_argument: $ => choice($._expression, $.struct_argument),
    struct_argument: $ => seq($.type_name, '{', repeat(choice($.field_argument, ',', ';')), '}'),
    field_argument: $ => seq(field('name', $.identifier), ':', $._call_argument),
    identifier: _ => /[a-zA-Z_][a-zA-Z_0-9]*/,
    number: _ => /0[xX][0-9a-fA-F]+|0[bB][01]+|[0-9]+/,
    boolean: _ => choice('true', 'false'),
    line_comment: _ => token(seq('//', /[^\r\n]*/)),
    block_comment: _ => token(seq('/*', /[^*]*\*+([^/*][^*]*\*+)*/, '/')),

    assembly: $ => seq('asm', optional($.assembly_name_list), optional($.assembly_outputs),
      optional($.assembly_clobbers), $.assembly_block),
    assembly_block: $ => seq('{', repeat(choice($.assembly_block, $.assembly_comment,
      $.assembly_string, $.assembly_number, $.assembly_word, $.assembly_punctuation)), '}'),
    assembly_comment: _ => token(seq(';', /[^\r\n]*/)),
    assembly_string: _ => token(choice(
      /"([^"\\\r\n]|\\[^\r\n]|"")*"/,
      /'([^'\\\r\n]|\\[^\r\n]|'')*'/,
    )),
    assembly_number: _ => /\$[0-9a-fA-F]+|%[01]+|0[xX][0-9a-fA-F]+|0[bB][01]+|[0-9][0-9a-fA-F]*[hH]|[0-9]+/,
    assembly_word: _ => choice(/[.#]?[a-zA-Z_][a-zA-Z_0-9.]*/, /([Aa][Ff]|[Bb][Cc]|[Dd][Ee]|[Hh][Ll])'/),
    assembly_punctuation: _ => /[^\s{}a-zA-Z_0-9;"']|["']/,
  },
});
