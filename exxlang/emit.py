"""Assembler output shared by registered target dialects."""

from collections import deque
from hashlib import sha256

from .ir import Directive, StaticData
from .registry import targets
from .syntax import AsmBlock


def _asm_lines(text):
    lines = text.split("\n")
    if len(lines) > 1:
        # Whitespace on the two delimiter lines belongs to the EXX block.
        if not lines[-1].strip():
            lines.pop()
        if not lines[0].strip():
            lines.pop(0)
    return lines


class Assembler:
    name: str
    platforms: tuple[str, ...]

    def header(self, procedures, section):
        return []

    def operands(self, items):
        return ", ".join(items)

    def structure_lines(self, structures):
        return []

    def constant(self, name, value):
        return f"{name} EQU {value}"

    def emit(self, procedures, section, includes, *, layouts_only=False):
        comments = deque(getattr(procedures, "comments", ()))
        assembly = getattr(procedures, "assembly", ())
        data = getattr(procedures, "data", ())
        structures = getattr(procedures, "structs", ())
        directives = getattr(procedures, "directives", ())
        if not isinstance(procedures, list):
            procedures = list(procedures)
        lines = ["; Generated by EXX."]

        def emit_comments(before=None, indent=""):
            while comments and (before is None or comments[0].offset < before):
                raw = comments.popleft().value
                body = raw[2:] if raw.startswith("//") else raw[2:-2]
                for line in body.split("\n"):
                    lines.append((indent + "; " + line.removeprefix(" ")).rstrip())

        for path in includes:
            if not path or any(char in path for char in '"\r\n\0'):
                raise ValueError(f"invalid assembler include path {path!r}")
            lines.append(f'    INCLUDE "{path}"')
        if not layouts_only:
            lines.extend(self.header(procedures, section))
        structure_lines = self.structure_lines(structures)
        if layouts_only:
            if structures and not structure_lines:
                raise ValueError(f"{self.name} has no structure declarations; select an assembler-specific target")
            return "\n".join(lines + structure_lines) + "\n"
        lines.extend(structure_lines)
        for item in sorted([*procedures, *assembly, *data, *directives], key=lambda item: item.start):
            lines.append("")
            emit_comments(item.start)
            if isinstance(item, AsmBlock):
                lines.extend(_asm_lines(item.text))
                continue
            if isinstance(item, Directive):
                value = self.operands((item.value,))
                lines.append(self.constant(item.name, value) if item.name else f"    ORG {value}")
                continue
            if isinstance(item, StaticData):
                directive = {8: "defb", 16: "defw"}[item.width]
                lines.extend((f"{item.name}:", f"    {directive} {self.operands((item.initializer,))}"))
                continue
            procedure = item
            if procedure.platform not in self.platforms:
                raise ValueError(f"{self.name} cannot emit {procedure.platform} instructions")
            lines.append(f"{procedure.name}:")
            for ins in procedure.instructions:
                emit_comments(ins.source_offset, "    ")
                if ins.mnemonic == "asm":
                    lines.extend(_asm_lines(ins.operands[0]))
                    continue
                operands = self.operands(ins.operands)
                if ins.mnemonic == "label":
                    lines.append(f"{operands}:")
                else:
                    lines.append(f"    {ins.mnemonic}" + (f" {operands}" if operands else ""))
            emit_comments(procedure.end, "    ")
        emit_comments()
        return "\n".join(lines) + "\n"


def emit(procedures, target, section="code_user", includes=()):
    return targets.create(target).emit(procedures, section, includes)


def structure_guard(struct):
    # Identical declarations can be included twice. A changed layout reaches
    # the assembler's duplicate-definition diagnostic instead of being hidden.
    return "EXX__STRUCT_" + sha256(repr(struct).encode("ascii")).hexdigest()[:16].upper()
