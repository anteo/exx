"""Format selected Z80 instructions for sjasmplus and z88dk."""

from __future__ import annotations

from collections.abc import Iterable
import re
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from .compiler import Procedure


TARGETS = ("sjasmplus", "z88dk")
_NAME = re.compile(r"[A-Za-z_][A-Za-z0-9_]*\Z")
_SYMBOL = re.compile(
    r"(?<![\w.])[A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z_][A-Za-z0-9_]*)*"
)


def emit(
    procedures: Iterable[Procedure],
    target: str,
    section: str = "code_user",
    includes: Iterable[str] = (),
) -> str:
    if target not in TARGETS:
        raise ValueError(f"unknown assembler target {target!r}")
    if target == "z88dk" and not _NAME.fullmatch(section):
        raise ValueError(f"invalid z88dk section name {section!r}")

    procedures = list(procedures)
    lines = ["; Generated by EXX."]
    for path in includes:
        if not path or any(char in path for char in '"\r\n\0'):
            raise ValueError(f"invalid assembler include path {path!r}")
        lines.append(f'    INCLUDE "{path}"')

    if target == "z88dk":
        local_names = {procedure.name for procedure in procedures}
        externals = set().union(*(procedure.externals for procedure in procedures))
        lines.extend(("", f"    SECTION {section}"))
        lines.extend(f"    PUBLIC {procedure.name}" for procedure in procedures)
        lines.extend(f"    EXTERN {name}" for name in sorted(externals - local_names))
        symbols = {name: name for name in local_names | externals}

        def render_symbol(match: re.Match[str]) -> str:
            original = match[0]
            rendered = original.replace(".", "_")
            previous = symbols.setdefault(rendered, original)
            if previous != original:
                raise ValueError(
                    f"z88dk symbol collision: {previous!r} and {original!r} both map to {rendered!r}"
                )
            return rendered

    for procedure in procedures:
        lines.extend(("", f"{procedure.name}:"))
        for instruction in procedure.instructions:
            mnemonic = instruction.mnemonic
            operands = instruction.operands
            rendered = ", ".join(operands)
            if target == "z88dk":
                rendered = _SYMBOL.sub(render_symbol, rendered)
            if mnemonic == "label":
                lines.append(f"{rendered}:")
                continue
            suffix = f" {rendered}" if rendered else ""
            lines.append(f"    {mnemonic}{suffix}")
    return "\n".join(lines) + "\n"
