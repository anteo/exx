import unittest

from exxlang.compiler import compile_source
from exxlang.emit import emit


class CommentTests(unittest.TestCase):
    def test_comments_follow_code_through_lowering(self):
        source = """// First routine.
f(flag → CF) {
    if (flag) /* early exit */ return
    /* first line
       second line */
    keep(BC) { B = 1 /* between writes */ ; B = 2 }
}
// Second routine.
g() {}
// End of module."""
        for target in ("asm", "z80asm"):
            with self.subTest(target=target):
                output = emit(compile_source(source), target)
                sequence = ("; First routine.", "f:", "; early exit", "ret c",
                            "; first line", "second line", "push bc", "ld b, 1",
                            "; between writes", "ld b, 2", "pop bc", "; Second routine.",
                            "g:", "ret", "; End of module.")
                offset = 0
                for item in sequence:
                    offset = output.index(item, offset) + len(item)

    def test_comments_survive_without_generated_code(self):
        output = emit(compile_source("// external routine\nextern run()\n/* end */"), "asm")
        self.assertEqual(output.splitlines(), ["; Generated by EXX.", "; external routine", "; end"])

    def test_comment_in_unreachable_code_survives_once(self):
        output = emit(compile_source("f() { return; /* unreachable */ return }"), "asm")
        self.assertEqual(output.count("; unreachable"), 1)
        self.assertEqual(output.count("    ret\n"), 1)
